/**
 * Uitroltaak redirects-oude-site-v1: de URL's van de huidige lekkergeelbusje.nl naar de nieuwe pagina's,
 * als 301 in Rank Math > Redirections. Per oude URL staan doelen op volgorde; het eerste dat op deze site bestaat,
 * wordt het. Bestaat de oude URL op de nieuwe site gewoon (bijv. /over-ons/), dan komt er geen redirect.
 */
function thema_redirects_oude_site() {
	if ( ! class_exists( '\RankMath\Redirections\Redirection' ) ) {
		return 'redirections-module van rank math niet beschikbaar';
	}
	/* Doelen: 'p:' = pagina (pad), 'g:' = gelegenheid (slug), '/' = homepage. */
	$kaart = array(
		'contacteer-ons'              => array( 'p:contact' ),
		'offerte-aanvragen-social-media' => array( 'p:offerte-aanvragen' ), // Bestaande redirect op de huidige site.
		'offerte-aanvragen'           => array( 'p:offerte-aanvragen' ),
		'privacyverklaring'           => array( 'p:privacyverklaring' ),
		'over-ons'                    => array( 'p:over-ons' ),
		'bruiloften'                  => array( 'g:bruiloft', 'p:gelegenheden' ),
		'vrijgezellenfeesten'         => array( 'g:vrijgezellenfeest', 'p:gelegenheden' ),
		'festivals'                   => array( 'g:festival', 'p:gelegenheden' ),
		'verjaardagen'                => array( 'g:verjaardag', 'g:trip-met-vrienden', 'p:gelegenheden' ),
		'keukenhof'                   => array( 'g:keukenhof', 'g:trip-met-vrienden', 'p:gelegenheden' ),
		'kerstmarkten'                => array( 'g:kerstmarkt', 'g:trip-met-vrienden', 'p:gelegenheden' ),
		'waarvoor-een-feestbus'       => array( 'p:gelegenheden' ),
		'werken-bij'                  => array( 'p:werken-bij', 'p:over-ons' ),
		'onze-bussen'                 => array( 'p:onze-bussen', 'p:bussen', '/' ),
		'bussen'                      => array( 'p:bussen', 'p:onze-bussen', '/' ),
		'sfeerimpressies'             => array( 'p:bussen', 'p:onze-bussen', 'p:over-ons' ),
		'album'                       => array( 'p:bussen', 'p:onze-bussen', 'p:over-ons' ),
		'partybussen-in-brabant'      => array( 'p:locaties', '/' ),
		'partybussen-in-utrecht'      => array( 'p:locaties/utrecht', 'p:locaties', '/' ),
		'partybussen-in-limburg'      => array( 'p:locaties', '/' ),
		'partybussen-in-gelderland'   => array( 'p:locaties', '/' ),
	);
	$uit = array();
	foreach ( $kaart as $oud => $doelen ) {
		/* Bestaat de oude URL hier al als pagina, dan niets doen. */
		$hier = get_page_by_path( $oud );
		if ( $hier && 'publish' === $hier->post_status ) {
			$uit[ $oud ] = 'bestaat al';
			continue;
		}
		$naar = thema_redirect_doel( $doelen );
		if ( ! $naar || untrailingslashit( $naar ) === untrailingslashit( home_url( '/' . $oud ) ) ) {
			$uit[ $oud ] = 'geen doel';
			continue;
		}
		$id          = thema_redirect_opslaan( array( array( 'pattern' => $oud, 'comparison' => 'exact' ) ), $naar );
		$uit[ $oud ] = $id ? $naar : 'mislukt';
	}

	/* De losse buspagina's (/bussen/lekker-geel-busje-9/ e.d.) naar de bussenpagina. */
	$bussen = thema_redirect_doel( array( 'p:bussen', 'p:onze-bussen', '/' ) );
	if ( $bussen ) {
		$id                   = thema_redirect_opslaan( array( array( 'pattern' => '^bussen/.+', 'comparison' => 'regex' ) ), $bussen );
		$uit['bussen/{bus}'] = $id ? $bussen : 'mislukt';
	}

	/* Overblijfselen van Elementor/ElementsKit-templates. */
	$id                         = thema_redirect_opslaan( array( array( 'pattern' => 'elementskit_template', 'comparison' => 'start' ) ), home_url( '/' ) );
	$uit['elementskit_template'] = $id ? home_url( '/' ) : 'mislukt';

	return $uit;
}

function thema_redirect_doel( $doelen ) {
	foreach ( $doelen as $doel ) {
		if ( '/' === $doel ) {
			return home_url( '/' );
		}
		$soort = substr( $doel, 0, 2 );
		$pad   = substr( $doel, 2 );
		$post  = 'g:' === $soort ? get_page_by_path( $pad, OBJECT, 'gelegenheid' ) : get_page_by_path( $pad );
		if ( $post && in_array( $post->post_status, array( 'publish', 'draft', 'pending', 'future' ), true ) ) {
			/* Ook een concept telt: bij livegang staat hij gepubliceerd. De permalink van een concept is nog leeg. */
			if ( 'publish' === $post->post_status ) {
				return get_permalink( $post );
			}
			return 'g:' === $soort ? home_url( '/gelegenheden/' . $post->post_name . '/' ) : home_url( '/' . get_page_uri( $post ) . '/' );
		}
	}
	return '';
}

function thema_redirect_opslaan( $bronnen, $naar ) {
	$r = \RankMath\Redirections\Redirection::from( array(
		'sources'     => $bronnen,
		'url_to'      => $naar,
		'header_code' => '301',
		'status'      => 'active',
	) );
	if ( method_exists( $r, 'is_infinite_loop' ) && $r->is_infinite_loop() ) {
		return 0;
	}
	return (int) $r->save();
}
