		@unlink( $tijdelijk ); // phpcs:ignore
		return 'opslaan mislukt: ' . $id->get_error_message();
	}
	update_post_meta( $id, '_wp_attachment_image_alt', $alt );
	update_option( 'thema_logo_google', (int) $id, false );
