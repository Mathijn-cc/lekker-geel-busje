/**
 * Uitroltaak rank-math-velden-v1: de handmatige SEO-velden van het thema naar Rank Math.
 * Een veld dat in Rank Math al gevuld is, blijft staan. Ook: focus keyword waar dat uit de titel volgt,
 * en de bedankpagina's op noindex.
 */
function thema_rank_math_velden() {
	if ( ! defined( 'RANK_MATH_VERSION' ) ) {
		return 'rank math staat niet aan';
	}
	$uit = array( 'titels' => 0, 'omschrijvingen' => 0, 'focus' => 0, 'noindex' => 0 );
	$ids = get_posts( array(
		'post_type'      => array( 'page', 'gelegenheid', 'post' ),
		'post_status'    => array( 'publish', 'draft', 'pending', 'future', 'private' ),
		'posts_per_page' => -1,
		'fields'         => 'ids',
	) );
	foreach ( $ids as $id ) {
		$titel = trim( (string) get_post_meta( $id, 'seo_titel', true ) );
		if ( '' !== $titel && '' === trim( (string) get_post_meta( $id, 'rank_math_title', true ) ) ) {
			update_post_meta( $id, 'rank_math_title', thema_seo_titel_naar_rank_math( $titel ) );
			$uit['titels']++;
		}

		$tekst = trim( wp_strip_all_tags( (string) get_post_meta( $id, 'seo_omschrijving', true ) ) );
		if ( '' === $tekst && 'gelegenheid' === get_post_type( $id ) ) {
			$tekst = trim( wp_strip_all_tags( (string) get_post_meta( $id, 'ondertitel', true ) ) );
		}
		if ( '' !== $tekst && '' === trim( (string) get_post_meta( $id, 'rank_math_description', true ) ) ) {
			update_post_meta( $id, 'rank_math_description', $tekst );
			$uit['omschrijvingen']++;
		}

		if ( '' === trim( (string) get_post_meta( $id, 'rank_math_focus_keyword', true ) ) ) {
			$focus = thema_rank_math_focus( $id, $titel );
			if ( $focus ) {
				update_post_meta( $id, 'rank_math_focus_keyword', $focus );
				$uit['focus']++;
			}
		}
	}

	foreach ( thema_rank_math_bedankt_ids() as $id ) {
		update_post_meta( $id, 'rank_math_robots', array( 'noindex', 'follow' ) );
		$uit['noindex']++;
	}
	return $uit;
}

/**
 * Focus keyword: op een gelegenheid "partybus" + de gelegenheid, op de homepage "partybus huren",
 * op een artikel het deel van de titel voor de dubbele punt. Elders niets: liever leeg dan verzonnen.
 */
function thema_rank_math_focus( $id, $seo_titel = '' ) {
	if ( (int) get_option( 'page_on_front' ) === (int) $id ) {
		return 'partybus huren';
	}
	$type = get_post_type( $id );
	if ( 'gelegenheid' === $type ) {
		$naam = mb_strtolower( get_the_title( $id ) );
		return 'partybus ' . $naam;
	}
	if ( 'post' === $type ) {
		$bron = $seo_titel ?: get_the_title( $id );
		$bron = preg_replace( '/\s*[|]\s*' . preg_quote( get_bloginfo( 'name' ), '/' ) . '\s*$/u', '', $bron );
		if ( false !== strpos( $bron, ':' ) ) {
			return mb_strtolower( trim( strtok( $bron, ':' ) ) );
		}
	}
	return '';
}

