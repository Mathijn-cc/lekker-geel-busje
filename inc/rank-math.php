/**
 * Een vaste titel op het eind (" | Lekker Geel Busje") wordt de Rank Math-variabele, zodat het scheidingsteken
 * en de sitenaam op een plek in te stellen zijn.
 */
function thema_seo_titel_naar_rank_math( $titel ) {
	$titel = trim( (string) $titel );
	$naam  = get_bloginfo( 'name' );
	foreach ( array( ' | ' . $naam, ' - ' . $naam, ' – ' . $naam ) as $staart ) {
		if ( $naam && substr( $titel, -strlen( $staart ) ) === $staart ) {
			return substr( $titel, 0, -strlen( $staart ) ) . ' %sep% %sitename%';
		}
	}
	return $titel;
}

/**
 * Titel in Google zetten: in Rank Math en in het oude themaveld (de terugval als Rank Math uit staat).
 */
function thema_seo_titel_zetten( $titel, $id ) {
	$id = (int) $id;
	if ( ! $id ) {
		return;
	}
	update_post_meta( $id, 'seo_titel', $titel );
	update_post_meta( $id, '_seo_titel', 'field_seo_seo_titel' );
	update_post_meta( $id, 'rank_math_title', thema_seo_titel_naar_rank_math( $titel ) );
}

function thema_seo_omschrijving_zetten( $tekst, $id ) {
	$id = (int) $id;
	if ( ! $id ) {
		return;
	}
	update_post_meta( $id, 'seo_omschrijving', $tekst );
	update_post_meta( $id, '_seo_omschrijving', 'field_seo_seo_omschrijving' );
	update_post_meta( $id, 'rank_math_description', trim( wp_strip_all_tags( (string) $tekst ) ) );
}

