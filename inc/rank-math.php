 * "Straat 1\n5061 AB Oisterwijk" naar de adresvelden van Rank Math.
 */
function thema_rank_math_adres( $tekst ) {
	$regels = array_values( array_filter( array_map( 'trim', preg_split( '/\r?\n|,/', (string) $tekst ) ) ) );
	if ( count( $regels ) < 2 || false !== stripos( $tekst, 'straatnaam' ) ) {
		return array();
	}
	$postcode = '';
	$plaats   = $regels[1];
	if ( preg_match( '/^(\d{4}\s?[A-Z]{2})\s+(.+)$/i', $regels[1], $m ) ) {
		$postcode = strtoupper( preg_replace( '/\s+/', ' ', $m[1] ) );
		$plaats   = $m[2];
	}
	return array_filter( array(
		'streetAddress'   => $regels[0],
		'addressLocality' => $plaats,
		'addressRegion'   => 'Noord-Brabant',
		'postalCode'      => $postcode,
		'addressCountry'  => 'NL',
	) );
}

