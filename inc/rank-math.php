/* Geen "Generated by Rank Math"-regel bovenaan llms.txt. */
add_filter( 'rank_math/llms_txt/remove_credit', '__return_true' );

/* Bedankpagina's niet in llms.txt, pagina's in de volgorde van het menu. */
add_filter( 'rank_math/llms_txt/posts_query_args', function ( $args ) {
	$weg = thema_rank_math_bedankt_ids();
	if ( $weg ) {
		$args['post__not_in'] = array_merge( (array) ( $args['post__not_in'] ?? array() ), $weg );
	}
	if ( in_array( $args['post_type'] ?? '', array( 'page', 'gelegenheid' ), true ) ) {
		$args['orderby'] = array( 'menu_order' => 'ASC', 'title' => 'ASC' );
	}
	return $args;
} );

/* Bedankpagina's ook nooit in de sitemap van Rank Math. */
add_filter( 'rank_math/sitemap/entry', function ( $url, $type, $object ) {
	if ( 'post' === $type && $object instanceof WP_Post && function_exists( 'thema_is_bedankt' ) && thema_is_bedankt( $object ) ) {
		return false;
	}
	return $url;
}, 10, 3 );

function thema_rank_math_bedankt_ids() {
	$ids = array();
	foreach ( function_exists( 'thema_bedankt_slugs' ) ? thema_bedankt_slugs() : array() as $slug ) {
		$p = get_page_by_path( $slug );
		if ( $p ) {
			$ids[] = (int) $p->ID;
		}
	}
	return $ids;
}

/**
 * Afbeeldingen: een foto zonder alt-tekst krijgt de titel van de afbeelding uit de mediabibliotheek.
 * Rank Math doet dit alleen in de berichttekst; de blokken van het thema gebruiken wp_get_attachment_image.
 * Titels als IMG_1234 of DSC01234 tellen niet: dan liever een lege alt dan een nietszeggende.
 */
add_filter( 'wp_get_attachment_image_attributes', function ( $attr, $bijlage ) {
	if ( isset( $attr['alt'] ) && '' !== trim( $attr['alt'] ) ) {
		return $attr;
	}
	$titel = thema_beeld_titel_bruikbaar( get_the_title( $bijlage ) );
	if ( $titel ) {
		$attr['alt'] = $titel;
	}
	return $attr;
}, 20, 2 );

function thema_beeld_titel_bruikbaar( $titel ) {
	$titel = trim( str_replace( array( '-', '_' ), ' ', (string) $titel ) );
	if ( '' === $titel || preg_match( '/^(img|dsc|dscf|pxl|mvimg|whatsapp|screenshot|scherm|image|foto|photo)?\s*[\d\s]*$/i', $titel ) || preg_match( '/^(img|dsc|pxl|whatsapp image)\b/i', $titel ) ) {
		return '';
	}
	return ucfirst( preg_replace( '/\s+/', ' ', $titel ) );
}

/**
 * Schema: aanvullingen op de graaf van Rank Math.
 */
add_filter( 'rank_math/json_ld', function ( $data, $jsonld ) {
	$canonical = '';
	if ( class_exists( '\RankMath\Paper\Paper' ) ) {
		$canonical = (string) \RankMath\Paper\Paper::get()->get_canonical();
	}

	/* Het bedrijf: werkgebied en foto. Lekker Geel Busje rijdt door heel Nederland en daarbuiten. */
	if ( ! empty( $data['publisher'] ) && is_array( $data['publisher'] ) ) {
		$data['publisher']['areaServed'] = array( '@type' => 'Country', 'name' => 'Nederland' );
		$s = function_exists( 'thema_instellingen' ) ? thema_instellingen() : array();
		if ( empty( $data['publisher']['telephone'] ) && ! empty( $s['telefoon'] ) ) {
			$data['publisher']['telephone'] = thema_telefoon_internationaal( $s['telefoon'] );
		}
		if ( empty( $data['publisher']['email'] ) && ! empty( $s['email'] ) ) {
			$data['publisher']['email'] = $s['email'];
		}
	}

	/* Kruimelpad uit het thema (met de hub Gelegenheden en de blogonderwerpen), gekoppeld aan de webpagina. */
	if ( empty( $data['BreadcrumbList'] ) && function_exists( 'thema_kruimelpad' ) ) {
		$kruims = thema_kruimelpad();
		if ( count( $kruims ) > 1 ) {
			$items = array();
			foreach ( $kruims as $i => $kruim ) {
				$items[] = array(
					'@type'    => 'ListItem',
					'position' => $i + 1,
					'item'     => array(
						'@id'  => $kruim['url'],
						'name' => wp_strip_all_tags( html_entity_decode( $kruim['naam'], ENT_QUOTES, 'UTF-8' ) ),
					),
				);
			}
			$basis                  = $canonical ?: end( $kruims )['url'];
			$data['BreadcrumbList'] = array(
				'@type'           => 'BreadcrumbList',
				'@id'             => $basis . '#breadcrumb',
				'itemListElement' => $items,
			);
			if ( ! empty( $data['WebPage'] ) && is_array( $data['WebPage'] ) ) {
				$data['WebPage']['breadcrumb'] = array( '@id' => $basis . '#breadcrumb' );
			}
		}
	}

	/* Gelegenheid: de dienst die je boekt, met het bedrijf als aanbieder. */
	if ( is_singular( 'gelegenheid' ) ) {
		$id      = get_queried_object_id();
		$url     = get_permalink( $id );
		$dienst  = array(
			'@type'       => 'Service',
			'@id'         => $url . '#dienst',
			'name'        => 'Partybus voor je ' . mb_strtolower( get_the_title( $id ) ),
			'serviceType' => 'Partybus huren met chauffeur',
			'description' => function_exists( 'thema_seo_omschrijving' ) ? thema_seo_omschrijving() : '',
			'url'         => $url,
			'provider'    => array( '@id' => home_url( '/#organization' ) ),
			'areaServed'  => array( '@type' => 'Country', 'name' => 'Nederland' ),
		);
		if ( has_post_thumbnail( $id ) ) {
			$dienst['image'] = get_the_post_thumbnail_url( $id, 'breed' );
		}
		if ( ! empty( $data['WebPage'] ) && is_array( $data['WebPage'] ) ) {
			$dienst['mainEntityOfPage'] = array( '@id' => $data['WebPage']['@id'] ?? ( $url . '#webpage' ) );
		}
		$data['Service'] = array_filter( $dienst );
	}

	return $data;
}, 99, 2 );

/**
 * 085 006 2061 wordt +31 85 006 2061, zoals Google het in schema verwacht.
 */
function thema_telefoon_internationaal( $nummer ) {
	$cijfers = preg_replace( '/\D+/', '', (string) $nummer );
	if ( '' === $cijfers ) {
		return '';
	}
	if ( 0 === strpos( $cijfers, '0031' ) ) {
		$cijfers = substr( $cijfers, 4 );
	} elseif ( 0 === strpos( $cijfers, '31' ) && strlen( $cijfers ) === 11 ) {
		$cijfers = substr( $cijfers, 2 );
	} elseif ( 0 === strpos( $cijfers, '0' ) ) {
		$cijfers = substr( $cijfers, 1 );
	}
	return '+31 ' . substr( $cijfers, 0, 2 ) . ' ' . substr( $cijfers, 2, 3 ) . ' ' . substr( $cijfers, 5 );
}

